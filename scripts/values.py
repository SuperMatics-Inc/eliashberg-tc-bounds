"""Read the certificate results and write the values quoted in the paper to values.tex."""

from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path

PAPER = Path(__file__).resolve().parents[1]
CERTS = PAPER / 'certificates'
RECEIPT = CERTS / 'receipt-arb.json'
CERTIFY = CERTS / 'certify_arb.py'
INDEP = CERTS / 'receipt-rational.json'


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def mid(ball: str, digits: int) -> str:
    """Return the midpoint text from an Arb string of the form '[x +/- r]'."""
    x = re.match(r'\[([-0-9.eE+]+)', ball).group(1)
    return x


def trunc(x: str, places: int) -> str:
    """Truncate a decimal string to `places` decimals (a valid lower bound for positive x)."""
    whole, _, frac = x.partition('.')
    return whole + '.' + (frac + '0' * places)[:places]


def ceil_dec(x: float, places: int) -> str:
    import math

    s = 10**places
    return f'{math.ceil(x * s) / s:.{places}f}'


def main() -> None:
    r = json.loads(RECEIPT.read_text())
    cells = r['region2']['cells']
    worst = min(cells, key=lambda c: c['margin_rel'])
    rad = lambda b: float(re.search(r'\+/- ([0-9.eE+-]+)', b).group(1))  # noqa: E731
    vals = {
        'QzeroLow': trunc(mid(r['q0_lower_bound_of_g'], 0), 12),
        'RhoZero': ceil_dec(float(mid(r['rho0'], 0)) + rad(r['rho0']), 9),
        'GtwoUp': ceil_dec(float(mid(r['g2'], 0)) + rad(r['g2']), 6),
        'LamTwoFloat': f'{r["g2_detail"]["lam_float"]:.4e}'.replace('e-04', '\\times10^{-4}'),
        'BetaZero': ceil_dec(float(mid(r['g2_detail']['beta'], 0)), 6),
        'GammaZero': ceil_dec(float(mid(r['g2_detail']['gamma'], 0)), 6),
        'RegOneRho': ceil_dec(float(mid(r['region1']['rho'], 0)), 5),
        'RegOneRtilde': trunc(mid(r['region1']['r_tilde_low'], 0), 5),
        'RegOneDelta': ceil_dec(float(mid(r['region1']['delta'], 0)) * 1e5, 3) + '\\times10^{-5}',
        'RegOneR': trunc(mid(r['region1']['r_low'], 0), 5),
        'RegOneCrit': trunc(mid(r['region1']['criterion'], 0), 5),
        'RegTwoCells': str(len(cells)),
        'RegTwoN': str(r['region2']['N']),
        'RegTwoRatio': str(r['region2']['grid_ratio']),
        'RegTwoWorstMargin': f'{100 * worst["margin_rel"]:.2f}',
        'RegTwoWorstLo': worst['vl'],
        'RegTwoWorstHi': worst['vu'],
        'RegTwoBeta': ceil_dec(float(mid(r['region2']['beta'], 0)), 6),
        'RegThreeVal': ceil_dec(float(mid(r['region3']['bound'], 0)) + rad(r['region3']['bound']), 6),
        'RegThreeVb': r['region3']['v_b'],
        'ArbPrec': str(r['arb_prec_bits']),
        'CertSha': sha(CERTIFY),
        'ReceiptSha': sha(RECEIPT),
        'PlanSha': r['plan_sha256'],
        'FlintVer': r['flint'],
        'CertRuntime': str(r.get('runtime_s', '')),
    }
    if INDEP.exists():
        from fractions import Fraction

        q = json.loads(INDEP.read_text())
        fl = lambda s: float(Fraction(s))  # noqa: E731
        assert q['status'] == 'PASS'
        vals.update(
            {
                'IndepSha': sha(INDEP),
                'IndepScriptSha': q['verify_py_sha256'],
                'IndepN': str(q['parameters']['N']),
                'IndepVa': q['parameters']['v_a'],
                'IndepVb': q['parameters']['v_b'],
                'IndepRatio': q['parameters']['geometric_v_ratio'],
                'IndepCells': str(q['summary']['cell_count']),
                'IndepQ': q['parameters']['Q_lower_bound_for_g'],
                'IndepKappa': trunc(f'{fl(q["summary"]["small_min_normalized_gap_kappa"]):.10f}', 4),
                'IndepMidGap': trunc(f'{fl(q["summary"]["middle_min_gap_below_Q"]):.10f}', 5),
                'IndepLargeGap': trunc(f'{fl(q["summary"]["large_min_gap_below_Q"]):.10f}', 4),
                'IndepRuntime': f'{q["runtime_seconds"]:.2f}',
            }
        )
    lines = ['% Generated by scripts/values.py from certificates/receipt-*.json. Do not edit.']
    for k, v in vals.items():
        lines.append(f'\\newcommand{{\\{k}}}{{{v}}}')
    (PAPER / 'values.tex').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
